import { useEffect, useRef, useState } from "react"
import { ClipboardCopy, Loader2, Sparkles } from "lucide-react"
import { toast } from "sonner"
import { Button } from "@/components/ui/button"
import { Dialog, DialogContent, DialogDescription, DialogHeader, DialogTitle } from "@/components/ui/dialog"
import { requestComparisonBrief } from "@/data/comparison-advisor"
import { buildBriefSnapshot, type BriefSnapshot, type ComparisonBrief } from "@/lib/comparison-brief"
import type { RfqCaseDetail, Vendor } from "@/domain/types"
import type { Weights } from "@/lib/comparison"

const TITLES = { summary: "Executive summary", tradeoffs: "Price and delivery trade-offs", exceptions: "Missing information and exceptions", recommendation: "Conditional recommendation" } as const

export function ComparisonBriefPanel({ detail, selectedIds, vendors, weights }: { detail: RfqCaseDetail; selectedIds: string[]; vendors: Vendor[]; weights: Weights }) {
  const [open, setOpen] = useState(false)
  const [busy, setBusy] = useState(false)
  const [error, setError] = useState<string>()
  const [saved, setSaved] = useState<{ key: string; brief: ComparisonBrief; generatedAt: string }>()
  const requestState = useRef({ id: 0 })
  const [today, setToday] = useState(() => new Date().toISOString().slice(0, 10))
  useEffect(() => {
    const state = requestState.current
    const timer = setInterval(() => setToday(new Date().toISOString().slice(0, 10)), 30000)
    return () => { clearInterval(timer); state.id++ }
  }, [])
  let snapshot: BriefSnapshot | undefined
  let inputError: string | undefined
  try { snapshot = buildBriefSnapshot(detail, selectedIds, vendors, weights, today) }
  catch (cause) { inputError = cause instanceof Error ? cause.message : "Unable to prepare comparison evidence." }
  const key = JSON.stringify(snapshot)
  const stale = saved && saved.key !== key
  const generate = async () => {
    if (!snapshot) return
    const id = ++requestState.current.id
    setBusy(true)
    setError(undefined)
    let timeout: ReturnType<typeof setTimeout> | undefined
    try {
      const brief = await Promise.race([
        requestComparisonBrief(snapshot),
        new Promise<never>((_, reject) => { timeout = setTimeout(() => reject(new Error("The agent took too long. Please retry.")), 120000) }),
      ])
      if (id === requestState.current.id) setSaved({ key, brief, generatedAt: new Date().toLocaleString() })
    } catch (cause) {
      if (id === requestState.current.id) setError(cause instanceof Error ? cause.message : "Unable to generate the comparison brief.")
    } finally {
      clearTimeout(timeout)
      if (id === requestState.current.id) setBusy(false)
    }
  }
  const copy = async () => {
    if (!saved || stale || !snapshot) return
    try {
      await navigator.clipboard.writeText([
        `AI comparison brief - ${snapshot.company.toUpperCase()} / ${snapshot.caseId}`,
        `Generated ${saved.generatedAt}. Buyer review required. No award executed.`,
        ...Object.entries(TITLES).flatMap(([section, title]) => [title, ...saved.brief[section as keyof ComparisonBrief].map((claim) => `${claim.text} [${claim.evidenceIds.join(", ")}]`)]),
        "Evidence", ...snapshot.evidence.map((evidence) => `${evidence.id}: ${evidence.label}\n${JSON.stringify(evidence.facts)}`),
        "Data checks", ...snapshot.warnings,
      ].join("\n\n"))
      toast.success("AI brief and evidence copied")
    } catch (cause) {
      toast.error(cause instanceof Error ? cause.message : "Could not copy the brief.")
    }
  }
  return <>
    <Button onClick={() => setOpen(true)}><Sparkles /> AI comparison brief</Button>
    <Dialog open={open} onOpenChange={setOpen}>
      <DialogContent className="flex max-h-[90dvh] flex-col overflow-y-auto sm:max-w-2xl">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2"><Sparkles className="size-5 text-primary" /> AI comparison brief</DialogTitle>
          <DialogDescription>{detail.header.company.toUpperCase()} / {detail.header.rfqCaseId} · {selectedIds.length} selected replies. Generated by Copilot Studio; review all claims before making a decision.</DialogDescription>
        </DialogHeader>
        <p className="text-sm text-muted-foreground">Only selected offer facts and buyer scoring priorities are sent to the dedicated advisor. No emails, ERP updates or awards are performed.</p>
        <div className="flex flex-wrap gap-2">
          <Button disabled={busy || !!inputError} onClick={generate}>{busy ? <Loader2 className="animate-spin" /> : <Sparkles />}{busy ? "Analyzing selected replies..." : saved ? "Regenerate brief" : "Analyze selected replies"}</Button>
          {saved && !stale && <Button variant="outline" onClick={copy}><ClipboardCopy /> Copy with evidence</Button>}
        </div>
        <div aria-live="polite" role="status" className="text-sm">{busy && "Preparing an evidence-backed explanation. This may take a minute."}</div>
        {(inputError || error) && <p role="alert" className="rounded-lg border border-destructive p-3 text-sm text-destructive">{inputError ?? error}</p>}
        {stale && <p role="alert" className="rounded-lg border border-amber-500 p-3 text-sm">The comparison, data, priorities or date changed. Regenerate the brief; the previous analysis is no longer current.</p>}
        {snapshot && <details className="rounded-lg border p-3 text-sm" open={snapshot.warnings.length > 0}>
          <summary className="cursor-pointer font-medium">Data checks ({snapshot.warnings.length})</summary>
          {!snapshot.recommendationAllowed && <p className="mt-2 font-medium">Resolve comparability blockers before choosing a vendor.</p>}
          <ul className="mt-2 list-disc space-y-1 pl-4">{snapshot.warnings.map((warning) => <li key={warning}>{warning}</li>)}</ul>
          {!snapshot.warnings.length && <p className="mt-2">No configured data checks flagged an issue. This is not a compliance certification.</p>}
        </details>}
        {saved && !stale && snapshot && <div className="space-y-5">
          <p className="text-xs text-muted-foreground">Generated {saved.generatedAt} · AI-generated, not an approval</p>
          {Object.entries(TITLES).map(([section, title]) => <section key={section} className="space-y-2">
            <h3 className="font-semibold">{title}</h3>
            {saved.brief[section as keyof ComparisonBrief].map((claim, index) => <div key={index} className="rounded-lg bg-muted/50 p-3 text-sm">
              <p className="whitespace-pre-wrap">{claim.text}</p>
              <div className="mt-2 space-y-1">{claim.evidenceIds.map((id) => {
                const evidence = snapshot.evidence.find((item) => item.id === id)!
                return <details key={id} className="rounded border bg-background p-2">
                  <summary className="cursor-pointer text-xs font-medium text-primary">{evidence.label}</summary>
                  <pre className="mt-2 overflow-x-auto whitespace-pre-wrap break-words text-xs">{JSON.stringify(evidence.facts, null, 2)}</pre>
                </details>
              })}</div>
            </div>)}
          </section>)}
        </div>}
      </DialogContent>
    </Dialog>
  </>
}
