import { appConfig } from "@/config/app-config"
import {
  rfqCaseLineTable,
  rfqCaseTable,
  rfqReplyLineTable,
  rfqReplyTable,
  vendorTable,
  type TableMapping,
} from "@/config/dataverse-schema"
import { RFQ_STATUSES, type RfqCase, type RfqCaseDetail, type RfqCaseLine, type RfqReply, type RfqReplyLine, type RfqStatus, type Vendor } from "@/domain/types"
import type { RfqRepository } from "@/data/types"
import type { DataverseRow, GetAllOptions, TableService, TableServices } from "./discover"

const FORMATTED = "@OData.Community.Display.V1.FormattedValue"
/** Option set values for F&SC enums in Dataverse start at this offset. */
const ENUM_OFFSET = 200000000
const FNO_STATUSES: readonly RfqStatus[] = ["Created", "Sent", "Received", "Rejected", "Accepted", "Canceled", "Declined", "Removed"]

type Columns<M> = M extends TableMapping<infer K> ? K : never

function selectOf<K extends string>(mapping: TableMapping<K>) {
  return Object.values(mapping.columns).filter((c): c is string => typeof c === "string")
}

function odataString(value: string) {
  return `'${value.replace(/'/g, "''")}'`
}

class RowReader<K extends string> {
  private readonly mapping: TableMapping<K>
  private readonly row: DataverseRow

  constructor(mapping: TableMapping<K>, row: DataverseRow) {
    this.mapping = mapping
    this.row = row
  }

  raw(key: K): unknown {
    const column = this.mapping.columns[key]
    return column ? this.row[column] : undefined
  }

  formatted(key: K): string | undefined {
    const column = this.mapping.columns[key]
    const value = column ? this.row[`${column}${FORMATTED}`] : undefined
    return typeof value === "string" ? value : undefined
  }

  str(key: K): string | undefined {
    const value = this.raw(key)
    if (value === null || value === undefined || value === "") return undefined
    return String(value)
  }

  num(key: K): number | undefined {
    const value = this.raw(key)
    if (value === null || value === undefined || value === "") return undefined
    const n = Number(value)
    return Number.isFinite(n) ? n : undefined
  }

  date(key: K): string | undefined {
    const value = this.str(key)
    // F&SC uses 1900-01-01 as an "empty" date.
    if (!value || value.startsWith("1900-01-01")) return undefined
    return value
  }

  status(key: K): RfqStatus {
    const label = this.formatted(key) ?? this.raw(key)
    if (typeof label === "string") {
      const normalized = label.toLowerCase().replace(/\s/g, "").replace("cancelled", "canceled")
      const match = RFQ_STATUSES.find((s) => s.toLowerCase() === normalized)
      if (match) return match
    }
    const n = this.num(key)
    if (n !== undefined) {
      const index = n >= ENUM_OFFSET ? n - ENUM_OFFSET : n
      const status = FNO_STATUSES[index]
      if (status) return status
    }
    throw new Error(`Unknown RFQ status in ${this.mapping.logicalName}: ${String(this.raw(key))}`)
  }
}

/**
 * Reads RFQ data from F&SC through Dataverse virtual tables (mserp_*) using
 * the services generated by `pa app add data-source --connector dataverse`.
 */
export class DataverseRepository implements RfqRepository {
  readonly kind = "dataverse" as const
  private readonly services: TableServices

  constructor(services: TableServices) {
    this.services = services
  }

  private async fetchAll(service: TableService, options: GetAllOptions, limit: number = appConfig.maxRows): Promise<DataverseRow[]> {
    const rows: DataverseRow[] = []
    let skipToken: string | undefined
    do {
      const result = await service.getAll({ ...options, maxPageSize: Math.min(limit, 500), skipToken })
      if (!result.success) {
        const message = result.error instanceof Error ? result.error.message : String(result.error ?? "Unknown error")
        throw new Error(`Dataverse query failed: ${message}`)
      }
      if (!Array.isArray(result.data)) throw new Error("Dataverse returned an invalid row collection.")
      rows.push(...result.data)
      skipToken = result.skipToken
    } while (skipToken && rows.length < limit)
    if (skipToken || rows.length > limit) throw new Error(`Dataverse query exceeded ${limit} rows. Narrow the legal-entity scope before continuing.`)
    return rows
  }

  private companyFilter(column: string | null, company?: string) {
    if (!column || !company) throw new Error("Select a legal entity before loading F&O data.")
    return `${column} eq ${odataString(company.toLowerCase())}`
  }

  private and(...parts: (string | undefined)[]) {
    const filters = parts.filter(Boolean)
    return filters.length ? filters.join(" and ") : undefined
  }

  private toCase(row: DataverseRow): RfqCase {
    const r = new RowReader<Columns<typeof rfqCaseTable>>(rfqCaseTable, row)
    return {
      recordId: r.str("recordId") ?? r.str("rfqCaseId") ?? "",
      rfqCaseId: r.str("rfqCaseId") ?? "",
      name: r.str("name") ?? "(no name)",
      status: r.status("status"),
      company: (r.str("company") ?? appConfig.company ?? "").toUpperCase(),
      currency: r.str("currency") ?? "",
      procurementCategory: r.str("procurementCategory"),
      requester: r.str("requester"),
      createdDate: r.date("createdDate"),
      expiryDate: r.date("expiryDate"),
      requestedDeliveryDate: r.date("requestedDeliveryDate"),
      deliveryTerms: r.str("deliveryTerms"),
    }
  }

  private toCaseLine(row: DataverseRow): RfqCaseLine {
    const r = new RowReader<Columns<typeof rfqCaseLineTable>>(rfqCaseLineTable, row)
    const priceQuantity = r.num("priceQuantity") || 1
    return {
      recordId: r.str("recordId") ?? "",
      rfqCaseId: r.str("rfqCaseId") ?? "",
      lineNumber: r.num("lineNumber") ?? 0,
      itemNumber: r.str("itemNumber") ?? "",
      itemName: r.str("itemName") ?? r.str("itemNumber") ?? "",
      quantity: r.num("quantity") ?? 0,
      unit: r.str("unit") ?? "",
      procurementCategory: r.str("procurementCategory"),
      requestedDeliveryDate: r.date("requestedDeliveryDate"),
      targetUnitPrice: r.num("targetUnitPrice") ? r.num("targetUnitPrice")! / priceQuantity : undefined,
    }
  }

  private toReply(row: DataverseRow): RfqReply {
    const r = new RowReader<Columns<typeof rfqReplyTable>>(rfqReplyTable, row)
    return {
      recordId: r.str("recordId") ?? r.str("rfqId") ?? "",
      rfqId: r.str("rfqId") ?? "",
      rfqCaseId: r.str("rfqCaseId") ?? "",
      vendorAccount: r.str("vendorAccount") ?? "",
      vendorName: r.str("vendorName") ?? r.str("vendorAccount") ?? "",
      status: r.status("status"),
      currency: r.str("currency") || (typeof row.mserp_currencycode === "string" ? row.mserp_currencycode : ""),
      sentDate: r.date("sentDate"),
      replyDate: r.date("replyDate"),
      validUntil: r.date("validUntil"),
      deliveryDate: r.date("deliveryDate"),
      paymentTerms: r.str("paymentTerms"),
      deliveryTerms: r.str("deliveryTerms"),
      notes: r.str("notes"),
    }
  }

  private toReplyLine(row: DataverseRow): RfqReplyLine {
    const r = new RowReader<Columns<typeof rfqReplyLineTable>>(rfqReplyLineTable, row)
    const quantity = r.num("quantity") ?? 0
    const unitPrice = (r.num("unitPrice") ?? 0) / (r.num("priceQuantity") || 1)
    const discountPct = r.num("discountPct") ?? 0
    const netAmount = r.num("netAmount") ?? quantity * unitPrice * (1 - discountPct / 100)
    return {
      recordId: r.str("recordId") ?? "",
      rfqId: r.str("rfqId") ?? "",
      lineNumber: r.num("lineNumber") ?? 0,
      itemNumber: r.str("itemNumber") ?? "",
      quantity,
      unitPrice,
      discountPct,
      netAmount,
      leadTimeDays: r.num("leadTimeDays"),
      deliveryDate: r.date("deliveryDate"),
      quoted: unitPrice > 0,
    }
  }

  private async replyLinesFor(rfqIds: string[], company?: string): Promise<RfqReplyLine[]> {
    const rfqIdColumn = rfqReplyLineTable.columns.rfqId!
    const lines: RfqReplyLine[] = []
    // Keep OData filters short: query in chunks of 25 vendor RFQs.
    for (let i = 0; i < rfqIds.length; i += 25) {
      const chunk = rfqIds.slice(i, i + 25)
      const idsFilter = chunk.map((id) => `${rfqIdColumn} eq ${odataString(id)}`).join(" or ")
      const filter = this.and(
        `(${idsFilter})`,
        this.companyFilter(rfqReplyLineTable.columns.company, company),
        `${rfqReplyLineTable.columns.alternate} eq ${ENUM_OFFSET}`,
      )
      const rows = await this.fetchAll(this.services.rfqReplyLine, { select: selectOf(rfqReplyLineTable), filter }, 5000)
      lines.push(...rows.map((row) => this.toReplyLine(row)))
    }
    return lines
  }

  async listCompanies(): Promise<string[]> {
    const column = rfqCaseTable.columns.company!
    const rows = await this.fetchAll(this.services.rfqCase, { select: [column] }, 10000)
    return [...new Set(rows.map((row) => {
      const value = row[column]
      if (typeof value !== "string" || !value) throw new Error("An RFQ header has no legal entity.")
      return value.toLowerCase()
    }))].sort()
  }

  private groupCases(rows: DataverseRow[]): RfqCase[] {
    const grouped = new Map<string, RfqCase[]>()
    for (const row of rows) {
      const header = this.toCase(row)
      const key = `${header.company}:${header.rfqCaseId}`
      grouped.set(key, [...(grouped.get(key) ?? []), header])
    }
    return [...grouped.values()].map((headers) => {
      // A vendor decision must not close a case while other vendors are pending.
      const statuses = headers.map((header) => header.status)
      const status = (["Received", "Sent", "Created", "Accepted", "Rejected", "Declined", "Canceled", "Removed"] as const)
        .find((candidate) => statuses.includes(candidate))!
      return { ...headers[0], status }
    })
  }

  async listRfqCases(company?: string): Promise<RfqCase[]> {
    const c = rfqCaseTable.columns
    const rows = await this.fetchAll(this.services.rfqCase, {
      select: selectOf(rfqCaseTable),
      filter: this.companyFilter(c.company, company),
      orderBy: c.createdDate ? [`${c.createdDate} desc`] : undefined,
    })
    return this.groupCases(rows)
  }

  private async replyHeaders(company?: string, rfqCaseId?: string): Promise<RfqReply[]> {
    const [rows, vendors] = await Promise.all([
      this.fetchAll(this.services.rfqReply, {
        select: [...selectOf(rfqReplyTable), "mserp_currencycode"],
        filter: this.and(
          this.companyFilter(rfqReplyTable.columns.company, company),
          rfqCaseId ? `${rfqReplyTable.columns.rfqCaseId} eq ${odataString(rfqCaseId)}` : undefined,
        ),
      }, appConfig.maxRows * 4),
      this.listVendors(company),
    ])
    const names = new Map(vendors.map((vendor) => [vendor.accountNumber, vendor.name]))
    const replies = rows.map((row) => this.toReply(row))
    return replies.map((reply) => ({ ...reply, vendorName: names.get(reply.vendorAccount) || reply.vendorAccount }))
  }

  async listReplies(company?: string): Promise<RfqReply[]> {
    const replies = await this.replyHeaders(company)
    const answered = replies.filter((r) => r.status === "Received" || r.status === "Accepted" || r.status === "Rejected")
    const lines = await this.replyLinesFor(answered.map((r) => r.rfqId), company)
    const totals = new Map<string, number>()
    for (const line of lines) totals.set(line.rfqId, (totals.get(line.rfqId) ?? 0) + line.netAmount)
    return replies.map((r) => ({ ...r, totalAmount: totals.get(r.rfqId) }))
  }

  async getRfqCase(rfqCaseId: string, company?: string): Promise<RfqCaseDetail | null> {
    const caseFilter = (column: string | null) => (column ? `${column} eq ${odataString(rfqCaseId)}` : undefined)

    const [headerRows, lineRows, replies] = await Promise.all([
      this.fetchAll(this.services.rfqCase, {
        select: selectOf(rfqCaseTable),
        filter: this.and(caseFilter(rfqCaseTable.columns.rfqCaseId), this.companyFilter(rfqCaseTable.columns.company, company)),
      }),
      this.fetchAll(this.services.rfqCaseLine, {
        select: selectOf(rfqCaseLineTable),
        filter: this.and(caseFilter(rfqCaseLineTable.columns.rfqCaseId), this.companyFilter(rfqCaseLineTable.columns.company, company)),
      }),
      this.replyHeaders(company, rfqCaseId),
    ])
    if (headerRows.length === 0) return null

    const lines = await this.replyLinesFor(replies.map((r) => r.rfqId), company)
    const byRfq = new Map<string, RfqReplyLine[]>()
    for (const line of lines) byRfq.set(line.rfqId, [...(byRfq.get(line.rfqId) ?? []), line])

    return {
      header: this.groupCases(headerRows)[0],
      lines: [...new Map(lineRows.map((row) => {
        const line = this.toCaseLine(row)
        return [line.lineNumber, line] as const
      })).values()].sort((a, b) => a.lineNumber - b.lineNumber),
      replies: replies.map((r) => {
        const replyLines = (byRfq.get(r.rfqId) ?? []).sort((a, b) => a.lineNumber - b.lineNumber)
        return { ...r, lines: replyLines, totalAmount: replyLines.length ? replyLines.reduce((s, l) => s + l.netAmount, 0) : undefined }
      }),
    }
  }

  async listVendors(company?: string): Promise<Vendor[]> {
    const v = vendorTable.columns
    const rows = await this.fetchAll(this.services.vendor, {
      select: selectOf(vendorTable),
      filter: this.companyFilter(v.company, company),
      orderBy: v.name ? [`${v.name} asc`] : undefined,
    }, 2000)
    return rows.map((row) => {
      const r = new RowReader<Columns<typeof vendorTable>>(vendorTable, row)
      return {
        accountNumber: r.str("accountNumber") ?? "",
        name: r.str("name") ?? r.str("accountNumber") ?? "",
        email: r.str("email"),
        vendorGroup: r.str("vendorGroup"),
        city: r.str("city"),
        country: r.str("country"),
      }
    })
  }
}
